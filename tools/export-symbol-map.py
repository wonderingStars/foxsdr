# Exports a compact RVA -> function-name map from a PDB, for the crash
# dashboard's SYMBOLIC GROUPING (foxsdrWebsite, crash.go).
#
# WHY THE SERVER NEEDS THIS FILE AT ALL. A crash report identifies a frame as
# module + offset, and the client's grouping signature is built from exactly
# that - which measured badly in the field within one release cycle of
# shipping it. The same vendor teardown fault filed on consecutive days landed
# in TWO signatures because a Windows update moved ntdll's offsets; and two
# UNRELATED faults (a fatal 0.62.0 retune and an absorbed 0.64.0 teardown, two
# different users) merged into ONE signature because RtlpWaitOnCriticalSection
# happened to sit at the same RVA in both machines' ntdll builds. Offsets into
# code we do not ship identify the victim's patch level, not the bug.
#
# The stable identity of a fault is the nearest frame in OUR OWN code, BY NAME
# - "SoapySource::teardownLocked" survives every Windows update, every vendor
# driver install, and every FoxSDR release. Names need the PDB, the PDB never
# leaves this machine (it is tens of megabytes and full of paths), and the
# server is a Linux box that could not read it anyway. So the build exports
# THIS: the function table alone, a few hundred kilobytes of JSON, keyed by
# the same build id the report's frames quote. The server looks a frame's
# offset up in the map for its build id and groups by what it finds.
#
# The map is generated by tools/archive-symbols.ps1 on every build, right
# after the PDB itself is archived, into the same symbol-server layout:
#
#     <archive>\<pdb name>\<GUID><AGE>\<pdb name>            the PDB
#     <archive>\<pdb name>\<GUID><AGE>\symmap.json.gz        this map
#
# Deploying a map to the dashboard is copying it to the server's
# data/symbols/<BUILDID>.json.gz - see foxsdrWebsite/symbolmaps/README.md.
#
# Requires dbghelp.dll, i.e. runs on Windows - the same constraint the whole
# symbol archive already has, which is why the map is exported at build time
# rather than resolved at ingest time.
#
