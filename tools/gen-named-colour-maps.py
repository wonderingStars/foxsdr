"""Writes src/core/colour_maps_named.hpp: the six named waterfall colour maps (viridis, magma, plasma, inferno, cividis, turbo) as 256 8-bit entries each.

    py -3.14 tools/gen-named-colour-maps.py <folder holding viridis.csv magma.csv plasma.csv inferno.csv cividis.csv turbo.csv> [out.hpp]

The tables are READ from files already on this machine (the pyqtgraph package of the radioconda install: pyqtgraph/colors/maps/*.csv, 256 lines of "r,g,b" floats from 0 to 1 each);
nothing is downloaded. Their licences are stated in those files' own headers and in the licence file beside them:
    viridis, magma, plasma, inferno  - CC0 1.0 (Nathaniel J. Smith, Stefan van der Walt, Eric Firing: "New matplotlib colormaps")
    cividis                          - CC0 1.0 (Jamie R. Nunez, Christopher R. Anderton, Ryan S. Renslow)
    turbo                            - Apache-2.0 (Anton Mikhailov, Google LLC, 2019)
Each float is rounded to the nearest 8-bit value. The generated header carries the notices.
"""
import os
import sys

NAMES = ["viridis", "magma", "plasma", "inferno", "cividis", "turbo"]


def read_map(folder, name):
    rows = []
    with open(os.path.join(folder, name + ".csv"), encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith(";"):
                continue
            r, g, b = (float(x) for x in line.split(","))
            rows.append((int(round(r * 255)), int(round(g * 255)), int(round(b * 255))))
    if len(rows) != 256:
        raise SystemExit("%s: %d entries, expected 256" % (name, len(rows)))
    return rows


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    folder = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join("src", "core", "colour_maps_named.hpp")
    lines = []
    lines.append("// colour_maps_named.hpp - GENERATED by tools/gen-named-colour-maps.py (do not edit): six named waterfall colour maps of 256 entries (8-bit RGB).")
    lines.append("//")
    lines.append("// ORIGIN AND LICENCE. The numbers were read from files already on the build machine (pyqtgraph 'colors/maps/<name>.csv', nothing downloaded) and rounded to 8 bits:")
    lines.append("//   viridis, magma, plasma, inferno: CC0 1.0 Universal (public domain dedication) - Nathaniel J. Smith, Stefan van der Walt and (viridis) Eric Firing, the matplotlib colormaps.")
    lines.append("//   cividis: CC0 1.0 Universal - Jamie R. Nunez, Christopher R. Anderton, Ryan S. Renslow.")
    lines.append("//   turbo: Apache License 2.0 - Copyright 2019 Google LLC, Anton Mikhailov (https://ai.googleblog.com/2019/08/turbo-improved-rainbow-colormap-for.html). The licence text goes in the notices file.")
    lines.append("//")
    lines.append("// SPDX-License-Identifier: PolyForm-Noncommercial-1.0.0 (this file's wrapper); the data keeps the licences above")
    lines.append("#pragma once")
    lines.append("")
    lines.append("#include <array>")
    lines.append("#include <cstdint>")
    lines.append("")
    lines.append("namespace cascade::core::colour::named {")
    lines.append("")
    lines.append("constexpr int kNamedCount = %d;" % len(NAMES))
    lines.append("// stable ids (settings keys) and the English names")
    lines.append("inline constexpr const char* kNamedIds[kNamedCount] = {%s};" % ", ".join('"%s"' % n for n in NAMES))
    lines.append("inline constexpr const char* kNamedNames[kNamedCount] = {%s};" % ", ".join('"%s"' % n.capitalize() for n in NAMES))
    lines.append("")
    lines.append("// kTables[map][entry] = {r, g, b}")
    lines.append("inline constexpr std::uint8_t kTables[kNamedCount][256][3] = {")
    for n in NAMES:
        rows = read_map(folder, n)
        lines.append("    {  // " + n)
        for i in range(0, 256, 8):
            lines.append("        " + " ".join("{%d,%d,%d}," % rows[j] for j in range(i, i + 8)))
        lines.append("    },")
    lines.append("};")
    lines.append("")
    lines.append("}  // namespace cascade::core::colour::named")
    lines.append("")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote", out)


if __name__ == "__main__":
    main()
