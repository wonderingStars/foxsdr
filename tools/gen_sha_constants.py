# Regenerates src/core/sys_sha_consts.inc: the SHA-256 and SHA-512 round constants and initial hash values, computed from their
# DEFINITION in FIPS 180-4 sections 4.2.2-4.2.3 and 5.3.3-5.3.5 (fractional parts of the cube / square roots of the first primes), with exact integer arithmetic.
# Run: python tools/gen_sha_constants.py > src/core/sys_sha_consts.inc
def primes(n):
    out = []; c = 2
    while len(out) < n:
        if all(c % p for p in out): out.append(c)
        c += 1
    return out

def iroot(x, k):
    lo, hi = 0, 1
    while hi ** k <= x: hi *= 2
    while lo < hi - 1:
        mid = (lo + hi) // 2
        if mid ** k <= x: lo = mid
        else: hi = mid
    return lo

def frac_root(p, k, bits):
    return iroot(p << (bits * k), k) & ((1 << bits) - 1)

def arr(name, vals, bits):
    w = bits // 4
    print("static const std::uint%d_t %s[%d] = {" % (bits, name, len(vals)))
    for i in range(0, len(vals), 4):
        print("    " + ", ".join(("0x%0*x%s" % (w, v, "ULL" if bits == 64 else "u")) for v in vals[i:i + 4]) + ",")
    print("};")

print("// GENERATED by tools/gen_sha_constants.py from FIPS 180-4; do not edit by hand.")
arr("kSha256K", [frac_root(p, 3, 32) for p in primes(64)], 32)
arr("kSha256H0", [frac_root(p, 2, 32) for p in primes(8)], 32)
arr("kSha512K", [frac_root(p, 3, 64) for p in primes(80)], 64)
arr("kSha512H0", [frac_root(p, 2, 64) for p in primes(8)], 64)
