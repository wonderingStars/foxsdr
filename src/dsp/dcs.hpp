// DCS (Digital-Coded Squelch, also called DPL, DCG, CDCSS, DTCS): the 83 standard codes, the
// (23,12) Golay word with bit-error correction, and a decoder for the 134.4 bit/s sub-audible
// stream that reports which code (and which polarity) is present.
//
// STANDALONE BLOCK. Nothing here is wired into the pipeline, the engine, the settings or the
// screen (docs/feature-records/signal-blocks.md, "Wiring hand-off", says where it goes).
//
// SOURCES AND WHAT IS AND IS NOT VERIFIED (clean room: published descriptions only).
//  * Signalling facts (134.4 bit/s; a 23-bit Golay (23,12) word of 12 data bits followed by
//    11 check bits; the last three data bits are a fixed 001, leaving 9 code bits written as a
//    three-digit octal number; the first bit sent is the LSB; 83 of the 512 codes are
//    standard; the code corrects up to 3 bit errors): Wikipedia, "Squelch" (DCS section) and
//    "Continuous Tone-Coded Squelch System", both read 2026-11-11; sigidwiki "DCS squelch"
//    (cited by the facts report; not opened here). The 83 codes are Wikipedia's list, which
//    cites TIA-603-E p. 10. THE STANDARD ITSELF WAS NOT READ.
//  * The (23,12) Golay code: Wikipedia, "Binary Golay code" (read 2026-11-11): minimum distance
//    7, generated by x^11+x^10+x^6+x^5+x^4+x^2+1, the other degree-11 factor
//    x^11+x^9+x^7+x^6+x^5+x+1 generates the reciprocal code.
//  * WHICH of the two codes, and in which bit order, DCS uses was NOT STATED in anything read
//    and is DERIVED here, not looked up: of the four candidate arrangements (either generator,
//    either mapping of the transmitted bits onto polynomial coefficients) exactly one pair of
//    equivalent forms makes the 83 standard codes free of "alignment collisions" (no cyclic
//    rotation of one standard code's word is the marked word of another standard code), which
//    is the stated reason only 83 of 512 codes are standard. The other pair has 34 such
//    collisions among the 83; a random choice of 83 codes has 12 or more. Used here:
//      transmitted bit t_j (t_0 first) is the coefficient of x^(22-j) of a codeword divisible
//      by g(x) = x^11+x^9+x^7+x^6+x^5+x+1 (0xAE3); t_0..t_8 are the code bits, LSB first,
//      t_9..t_11 = 0,0,1, t_12..t_22 = check bits.
//    CHECKED against a second, independent, published source: the RadioReference wiki's
//    "Inverted Codes" chart (https://wiki.radioreference.com/index.php/CDCSS, read 2026-11-11),
//    which lists, for each code, the code that an inverted transmission of it is read as. The
//    convention above reproduces that chart for ALL 83 standard codes (the reciprocal
//    arrangement reproduces 4 of 83). The ETSI standard TS 103 236 (CTCSS and DCS) was fetched
//    but is an encrypted PDF that could not be read here, and TIA-603-E was not read: the
//    convention is therefore verified against two third-party descriptions, NOT against a
//    standard's text and NOT against a real DCS signal. Labelled UNVERIFIED in the record.
//  * ON-AIR EQUIVALENCE (a property of the code, not a choice): the Golay code is cyclic and
//    contains the all-ones word, so the complement of a code's word is a codeword, and for most
//    standard codes a rotation of it is the marked word of ANOTHER standard code. "023 inverted"
//    is the same stream as "047 normal" (023/047, 025/244, 026/464, 031/627 ...). A decoder can
//    therefore not tell the two apart and neither can this one: it reports the NORMAL-polarity
//    reading as the code and the other reading as the alternate (dcs::inversePartner()).
//  * Inverted polarity: every bit complemented (documented as "inverse DPL"/"I" codes in the
//    facts report; the exact on-air definition is UNVERIFIED).
//
// RATES AND THREADS. The decoder takes the audio sample rate it is fed (any rate from 4 kHz
// up) and decimates internally. configure() allocates and belongs to set-up (control thread,
// DSP thread parked); process() is DSP-thread only and allocates, locks and logs nothing; the
// read-outs are atomics (any thread).
//
